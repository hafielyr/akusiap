-- =====================================================================
-- Quiz Practice App: database schema for PostgreSQL (Neon)
-- Source: quiz-app-erd.mermaid
--
-- Conventions
--   * snake_case, plural table names ("user" is reserved in PostgreSQL).
--   * Surrogate keys: bigint identity; users use uuid.
--   * Money: bigint in whole Rupiah (no decimals), tax-inclusive.
--   * Times: timestamptz (stored in UTC, shown in the user's time zone).
--   * Status fields: text + CHECK constraint (maps cleanly to C# enums
--     stored as strings in EF Core; no PostgreSQL enum types to migrate).
--   * Users are deactivated, never deleted, so most foreign keys RESTRICT.
--     Only pure child rows (options, join rows, attempt items, review logs)
--     cascade with their parent.
--
-- Run the whole file once on an empty database. It is wrapped in a
-- transaction: if any statement fails, nothing is created.
-- =====================================================================

BEGIN;

-- ===================== USERS & ACCESS =====================

CREATE TABLE users (
    id                  uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    email               text        NOT NULL,
    email_confirmed     boolean     NOT NULL DEFAULT false,
    phone_number        text,                                  -- +62 format, optional
    password_hash       text,                                  -- null for Google-only sign-in
    display_name        text        NOT NULL,
    preferred_language  text        NOT NULL DEFAULT 'id' CHECK (preferred_language IN ('id', 'en')),
    is_active           boolean     NOT NULL DEFAULT true,     -- deactivate instead of delete
    deactivated_at      timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    CHECK (is_active OR deactivated_at IS NOT NULL)
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));

CREATE TABLE roles (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  text   NOT NULL UNIQUE                               -- Learner, Teacher, Admin
);

CREATE TABLE user_roles (
    user_id  uuid   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id  bigint NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX ix_user_roles_role ON user_roles (role_id);

-- ===================== PLANS =====================

CREATE TABLE plans (
    id                  bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                text    NOT NULL UNIQUE CHECK (code IN ('Free', 'Learner', 'Teacher', 'Combined')),
    name                text    NOT NULL,
    includes_all_exams  boolean NOT NULL,
    includes_authoring  boolean NOT NULL,
    includes_classes    boolean NOT NULL,
    max_own_questions   integer CHECK (max_own_questions >= 0),  -- NULL = not decided yet, never "unlimited"
    max_own_exams       integer CHECK (max_own_exams >= 0),
    max_import_rows     integer CHECK (max_import_rows >= 0),
    is_active           boolean NOT NULL DEFAULT true
);

CREATE TABLE plan_prices (
    id               bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id          bigint  NOT NULL REFERENCES plans (id),
    duration_months  integer NOT NULL CHECK (duration_months IN (1, 3, 6, 12)),
    price_idr        bigint  NOT NULL CHECK (price_idr >= 0),
    is_active        boolean NOT NULL DEFAULT true,
    UNIQUE (plan_id, duration_months),
    UNIQUE (id, plan_id)                                       -- lets subscriptions check plan/price agree
);

-- ===================== CONTENT =====================

CREATE TABLE subjects (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text   NOT NULL UNIQUE,                       -- was Group
    description  text
);

CREATE TABLE topics (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id   bigint NOT NULL REFERENCES subjects (id),
    name         text   NOT NULL,                              -- was Type
    description  text,
    UNIQUE (subject_id, name)
);

CREATE TABLE rule_presets (
    id                  bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id       uuid    REFERENCES users (id),         -- NULL = system preset
    name                text    NOT NULL,
    time_limit_minutes  integer CHECK (time_limit_minutes > 0),  -- NULL = untimed
    question_count      integer CHECK (question_count > 0),      -- NULL = all questions
    hints_enabled       boolean NOT NULL DEFAULT true,
    shuffle_questions   boolean NOT NULL DEFAULT true,
    shuffle_options     boolean NOT NULL DEFAULT true,
    max_attempts        integer CHECK (max_attempts > 0),        -- NULL = unlimited
    pass_mark_percent   integer CHECK (pass_mark_percent BETWEEN 0 AND 100),
    show_answers        text    NOT NULL DEFAULT 'AfterSubmit'
                        CHECK (show_answers IN ('AfterEach', 'AfterSubmit', 'Never')),
    is_default          boolean NOT NULL DEFAULT false
);
CREATE INDEX ix_rule_presets_owner ON rule_presets (owner_user_id);
CREATE UNIQUE INDEX ux_rule_presets_one_system_default
    ON rule_presets (is_default) WHERE is_default AND owner_user_id IS NULL;

CREATE TABLE exams (
    id                      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id           uuid        REFERENCES users (id),  -- NULL = app exam
    owner_kind              text        NOT NULL CHECK (owner_kind IN ('App', 'Teacher', 'Learner')),
    subject_id              bigint      REFERENCES subjects (id),
    rule_preset_id          bigint      NOT NULL REFERENCES rule_presets (id),
    title                   text        NOT NULL,
    description             text,
    is_free                 boolean     NOT NULL DEFAULT false, -- free for registered users
    price_idr               bigint      CHECK (price_idr >= 0), -- app exams only
    access_days             integer     CHECK (access_days > 0),
    own_question_allowance  integer     NOT NULL DEFAULT 0 CHECK (own_question_allowance >= 0),
    status                  text        NOT NULL DEFAULT 'Draft'
                            CHECK (status IN ('Draft', 'Published', 'Unpublished', 'TakenDown')),
    is_shared               boolean     NOT NULL DEFAULT false,
    share_token             text        UNIQUE,                 -- link for non-users
    created_at              timestamptz NOT NULL DEFAULT now(),
    CHECK ((owner_kind = 'App') = (owner_user_id IS NULL)),
    CHECK (owner_kind = 'App' OR price_idr IS NULL),            -- only app exams are sold
    CHECK (NOT is_shared OR share_token IS NOT NULL)
);
CREATE INDEX ix_exams_owner ON exams (owner_user_id);
CREATE INDEX ix_exams_subject ON exams (subject_id);
CREATE INDEX ix_exams_rule_preset ON exams (rule_preset_id);
CREATE INDEX ix_exams_catalog ON exams (status, subject_id) WHERE owner_kind = 'App';

CREATE TABLE questions (
    id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id     uuid        REFERENCES users (id),        -- NULL = app question
    topic_id          bigint      NOT NULL REFERENCES topics (id),
    question_type     text        NOT NULL CHECK (question_type IN ('SingleChoice', 'MultiSelect', 'TrueFalse')),
    text              text        NOT NULL,
    explanation       text        NOT NULL,
    key_fact          text,                                     -- one line to memorize
    hint              text,
    difficulty        smallint    CHECK (difficulty BETWEEN 1 AND 5),
    source_note       text,                                     -- syllabus reference
    variant_group_id  uuid,                                     -- links variants of the same fact
    status            text        NOT NULL DEFAULT 'Draft' CHECK (status IN ('Draft', 'Active', 'Retired')),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_questions_owner ON questions (owner_user_id);
CREATE INDEX ix_questions_topic ON questions (topic_id);
CREATE INDEX ix_questions_variant_group ON questions (variant_group_id) WHERE variant_group_id IS NOT NULL;

CREATE TABLE question_options (
    id           bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  bigint  NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    text         text    NOT NULL,
    is_correct   boolean NOT NULL DEFAULT false,
    sort_order   integer NOT NULL
);
CREATE INDEX ix_question_options_question ON question_options (question_id);

CREATE TABLE exam_questions (
    exam_id      bigint  NOT NULL REFERENCES exams (id) ON DELETE CASCADE,
    question_id  bigint  NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    sort_order   integer NOT NULL,
    is_trial     boolean NOT NULL DEFAULT false,               -- fixed ~30 trial questions (BR-01)
    PRIMARY KEY (exam_id, question_id)
);
CREATE INDEX ix_exam_questions_question ON exam_questions (question_id);
CREATE INDEX ix_exam_questions_trial ON exam_questions (exam_id) WHERE is_trial;

-- ===================== PURCHASES & PAYMENTS =====================

CREATE TABLE saved_payment_methods (
    id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        uuid        NOT NULL REFERENCES users (id),
    gateway        text        NOT NULL DEFAULT 'DOKU' CHECK (gateway = 'DOKU'),
    type           text        NOT NULL CHECK (type IN ('CreditCard', 'DirectDebit')),
    display_label  text        NOT NULL,                       -- e.g. Visa ending 4417
    gateway_token  text        NOT NULL,                       -- DOKU token only, never card data
    is_active      boolean     NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_saved_payment_methods_user ON saved_payment_methods (user_id);

CREATE TABLE subscriptions (
    id                       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  uuid        NOT NULL REFERENCES users (id),
    plan_id                  bigint      NOT NULL REFERENCES plans (id),
    plan_price_id            bigint      NOT NULL,
    status                   text        NOT NULL DEFAULT 'AwaitingPayment'
                             CHECK (status IN ('AwaitingPayment', 'Active', 'Expired', 'Abandoned', 'Refunded')),
    current_period_start     timestamptz,
    current_period_end       timestamptz,
    renewal_mode             text        NOT NULL DEFAULT 'Manual' CHECK (renewal_mode IN ('Manual', 'AutoDebit')),
    saved_payment_method_id  bigint      REFERENCES saved_payment_methods (id),
    grace_until              timestamptz,                      -- failed auto-debit only
    reminder_7d_sent_at      timestamptz,
    reminder_1d_sent_at      timestamptz,
    gateway_subscription_id  text,                             -- auto-debit only
    created_at               timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (plan_price_id, plan_id) REFERENCES plan_prices (id, plan_id),
    CHECK (renewal_mode = 'Manual' OR saved_payment_method_id IS NOT NULL),
    CHECK (status <> 'Active' OR (current_period_start IS NOT NULL AND current_period_end > current_period_start))
);
-- BR-08: at most one live package of each type per user (renewals extend the same row)
CREATE UNIQUE INDEX ux_subscriptions_one_per_plan
    ON subscriptions (user_id, plan_id) WHERE status NOT IN ('Abandoned', 'Refunded');
CREATE INDEX ix_subscriptions_plan_price ON subscriptions (plan_price_id, plan_id);
CREATE INDEX ix_subscriptions_saved_method ON subscriptions (saved_payment_method_id);
CREATE INDEX ix_subscriptions_period_end ON subscriptions (current_period_end) WHERE status = 'Active';  -- reminders, expiry job

CREATE TABLE exam_purchases (
    id                 bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            uuid        NOT NULL REFERENCES users (id),
    exam_id            bigint      NOT NULL REFERENCES exams (id),
    price_paid_idr     bigint      NOT NULL CHECK (price_paid_idr >= 0),
    status             text        NOT NULL DEFAULT 'AwaitingPayment'
                       CHECK (status IN ('AwaitingPayment', 'Active', 'Expired', 'Abandoned', 'Refunded')),
    purchased_at       timestamptz,                            -- set when paid
    access_expires_at  timestamptz,                            -- from exams.access_days (BR-10)
    CHECK (status <> 'Active' OR (purchased_at IS NOT NULL AND access_expires_at IS NOT NULL))
);
-- BR-10: buying the same exam again extends the same row
CREATE UNIQUE INDEX ux_exam_purchases_one_per_exam
    ON exam_purchases (user_id, exam_id) WHERE status NOT IN ('Abandoned', 'Refunded');
CREATE INDEX ix_exam_purchases_exam ON exam_purchases (exam_id);

CREATE TABLE promo_codes (
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 text        NOT NULL,
    discount_percent     numeric(5,2) CHECK (discount_percent > 0 AND discount_percent <= 100),
    discount_amount_idr  bigint      CHECK (discount_amount_idr > 0),
    max_uses             integer     CHECK (max_uses > 0),     -- NULL = unlimited uses
    used_count           integer     NOT NULL DEFAULT 0 CHECK (used_count >= 0),
    expires_at           timestamptz,
    CHECK (num_nonnulls(discount_percent, discount_amount_idr) = 1)
);
CREATE UNIQUE INDEX ux_promo_codes_code ON promo_codes (upper(code));

CREATE TABLE payments (
    id                       bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number             text        NOT NULL UNIQUE,      -- readable reference for support
    user_id                  uuid        NOT NULL REFERENCES users (id),
    subscription_id          bigint      REFERENCES subscriptions (id),
    exam_purchase_id         bigint      REFERENCES exam_purchases (id),
    promo_code_id            bigint      REFERENCES promo_codes (id),
    saved_payment_method_id  bigint      REFERENCES saved_payment_methods (id),
    amount_idr               bigint      NOT NULL CHECK (amount_idr >= 0),   -- tax-inclusive (BR-20)
    discount_idr             bigint      NOT NULL DEFAULT 0 CHECK (discount_idr >= 0),
    tax_idr                  bigint      NOT NULL DEFAULT 0 CHECK (tax_idr >= 0),
    gateway_fee_idr          bigint      CHECK (gateway_fee_idr >= 0),       -- from settlement
    gateway                  text        NOT NULL DEFAULT 'DOKU' CHECK (gateway = 'DOKU'),
    method                   text        NOT NULL CHECK (method IN ('QRIS', 'VirtualAccount', 'EWallet', 'CreditCard')),
    channel                  text,                             -- BCA, BNI, BRI, MANDIRI, OVO, DANA, ...
    va_number                text,
    qr_string                text,
    deeplink_url             text,
    status                   text        NOT NULL DEFAULT 'Pending'
                             CHECK (status IN ('Pending', 'Paid', 'Expired', 'Canceled', 'Failed', 'Refunded')),
    expires_at               timestamptz,                      -- pay-before deadline
    invoice_number           text        NOT NULL UNIQUE,      -- DOKU order.invoice_number
    gateway_request_id       text,                             -- DOKU Request-Id of the checkout
    is_late_payment          boolean     NOT NULL DEFAULT false,  -- SUCCESS after Expired/Canceled (BR-23)
    failure_reason           text,
    retry_count              integer     NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    created_at               timestamptz NOT NULL DEFAULT now(),
    paid_at                  timestamptz,
    CHECK (num_nonnulls(subscription_id, exam_purchase_id) = 1),  -- pays for exactly one item
    CHECK (status NOT IN ('Paid', 'Refunded') OR paid_at IS NOT NULL),
    CHECK (method <> 'VirtualAccount' OR status <> 'Pending' OR va_number IS NOT NULL),
    CHECK (method <> 'QRIS' OR status <> 'Pending' OR qr_string IS NOT NULL)
);
-- BR-21: one pending payment per item
CREATE UNIQUE INDEX ux_payments_one_pending_subscription
    ON payments (subscription_id) WHERE status = 'Pending' AND subscription_id IS NOT NULL;
CREATE UNIQUE INDEX ux_payments_one_pending_exam_purchase
    ON payments (exam_purchase_id) WHERE status = 'Pending' AND exam_purchase_id IS NOT NULL;
CREATE INDEX ix_payments_user ON payments (user_id, created_at DESC);
CREATE INDEX ix_payments_promo ON payments (promo_code_id);
CREATE INDEX ix_payments_saved_method ON payments (saved_payment_method_id);
CREATE INDEX ix_payments_pending_deadline ON payments (expires_at) WHERE status = 'Pending';  -- status-check job (ADM-35)

CREATE TABLE refunds (
    id                      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id              bigint      NOT NULL REFERENCES payments (id),
    amount_idr              bigint      NOT NULL CHECK (amount_idr > 0),
    reason                  text        NOT NULL,
    status                  text        NOT NULL DEFAULT 'Requested'
                            CHECK (status IN ('Requested', 'Approved', 'Rejected', 'AwaitingDetails',
                                              'SentToDoku', 'Completed', 'Failed')),
    is_auto_approved        boolean     NOT NULL DEFAULT false,
    refund_route            text        CHECK (refund_route IN ('DirectToPayerApp', 'RefundLink')),
    refund_link_url         text,                              -- DOKU non-direct refund link
    refund_link_expires_at  timestamptz,
    attempt_count           integer     NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    requested_at            timestamptz NOT NULL DEFAULT now(),
    decided_by_user_id      uuid        REFERENCES users (id), -- admin; NULL when auto-approved
    decided_at              timestamptz,
    gateway_refund_id       text,
    CHECK (status IN ('Requested', 'Rejected') OR refund_route IS NOT NULL),
    CHECK (status <> 'AwaitingDetails' OR refund_link_url IS NOT NULL)
);
CREATE INDEX ix_refunds_payment ON refunds (payment_id);
CREATE INDEX ix_refunds_decided_by ON refunds (decided_by_user_id);
CREATE INDEX ix_refunds_open ON refunds (status) WHERE status IN ('Requested', 'AwaitingDetails', 'Failed');  -- ADM-36

CREATE TABLE payment_webhook_events (
    id                bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gateway           text        NOT NULL DEFAULT 'DOKU' CHECK (gateway = 'DOKU'),
    gateway_event_id  text        NOT NULL,                    -- DOKU Request-Id
    payment_id        bigint      REFERENCES payments (id),    -- NULL until matched
    payload           jsonb       NOT NULL,
    signature_valid   boolean     NOT NULL,
    received_at       timestamptz NOT NULL DEFAULT now(),
    processed_at      timestamptz,
    processing_error  text,
    UNIQUE (gateway, gateway_event_id)                         -- BR-26: processed once
);
CREATE INDEX ix_payment_webhook_events_payment ON payment_webhook_events (payment_id);

-- ===================== NOTIFICATIONS =====================

CREATE TABLE notifications (
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              uuid        NOT NULL REFERENCES users (id),
    channel              text        NOT NULL CHECK (channel IN ('Email', 'InApp')),
    template_code        text        NOT NULL
                         CHECK (template_code IN ('Receipt', 'Renewal7d', 'Renewal1d', 'RefundLink', 'ReviewDue')),
    language             text        NOT NULL DEFAULT 'id' CHECK (language IN ('id', 'en')),
    payload              jsonb       NOT NULL DEFAULT '{}'::jsonb,
    status               text        NOT NULL DEFAULT 'Queued'
                         CHECK (status IN ('Queued', 'Sent', 'Delivered', 'Read', 'Failed')),
    external_message_id  text,                                 -- email provider id
    scheduled_at         timestamptz NOT NULL DEFAULT now(),
    sent_at              timestamptz,
    error                text
);
CREATE INDEX ix_notifications_user ON notifications (user_id, scheduled_at DESC);
CREATE INDEX ix_notifications_queue ON notifications (scheduled_at) WHERE status = 'Queued';

-- ===================== CLASSES =====================

CREATE TABLE classrooms (
    id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_user_id  uuid        NOT NULL REFERENCES users (id),
    name             text        NOT NULL,
    invite_code      text        NOT NULL UNIQUE,
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_classrooms_teacher ON classrooms (teacher_user_id);

CREATE TABLE class_members (
    classroom_id  bigint      NOT NULL REFERENCES classrooms (id) ON DELETE CASCADE,
    user_id       uuid        NOT NULL REFERENCES users (id),
    joined_at     timestamptz NOT NULL DEFAULT now(),
    removed_at    timestamptz,
    PRIMARY KEY (classroom_id, user_id)
);
CREATE INDEX ix_class_members_user ON class_members (user_id);

CREATE TABLE class_assignments (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    classroom_id    bigint      NOT NULL REFERENCES classrooms (id),
    exam_id         bigint      NOT NULL REFERENCES exams (id),
    rule_preset_id  bigint      NOT NULL REFERENCES rule_presets (id),  -- locked rules (BR-15)
    opens_at        timestamptz NOT NULL,
    closes_at       timestamptz NOT NULL,
    CHECK (closes_at > opens_at)
);
CREATE INDEX ix_class_assignments_classroom ON class_assignments (classroom_id);
CREATE INDEX ix_class_assignments_exam ON class_assignments (exam_id);
CREATE INDEX ix_class_assignments_rule_preset ON class_assignments (rule_preset_id);

-- ===================== ATTEMPTS =====================

CREATE TABLE attempts (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              uuid         REFERENCES users (id),   -- NULL for guests
    guest_name           text,                                 -- shared-exam takers
    guest_token          uuid,                                 -- carry a trial into a new account
    exam_id              bigint       REFERENCES exams (id),   -- NULL for wrong-only, review, custom mix
    class_assignment_id  bigint       REFERENCES class_assignments (id),
    source               text         NOT NULL
                         CHECK (source IN ('Exam', 'Trial', 'Shared', 'WrongOnly', 'Review', 'CustomMix')),
    mode                 text         NOT NULL CHECK (mode IN ('Practice', 'Simulation', 'Flashcard')),
    status               text         NOT NULL DEFAULT 'InProgress'
                         CHECK (status IN ('InProgress', 'Submitted', 'Expired')),
    rules_snapshot       jsonb        NOT NULL,                -- rules in force when started
    started_at           timestamptz  NOT NULL DEFAULT now(),
    last_saved_at        timestamptz  NOT NULL DEFAULT now(),
    submitted_at         timestamptz,
    time_spent_seconds   integer      NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
    correct_count        integer      NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
    total_count          integer      NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    score_percent        numeric(5,2) CHECK (score_percent BETWEEN 0 AND 100),
    passed               boolean,
    CHECK (correct_count <= total_count),
    CHECK (user_id IS NOT NULL OR source = 'Trial' OR (source = 'Shared' AND guest_name IS NOT NULL)),
    CHECK (source NOT IN ('Exam', 'Trial', 'Shared') OR exam_id IS NOT NULL),
    CHECK (status <> 'Submitted' OR submitted_at IS NOT NULL)
);
CREATE INDEX ix_attempts_user ON attempts (user_id, started_at DESC);    -- session history (H-01)
CREATE INDEX ix_attempts_exam ON attempts (exam_id);
CREATE INDEX ix_attempts_class_assignment ON attempts (class_assignment_id);
CREATE INDEX ix_attempts_guest_token ON attempts (guest_token) WHERE guest_token IS NOT NULL;

CREATE TABLE attempt_items (
    id                  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id          bigint      NOT NULL REFERENCES attempts (id) ON DELETE CASCADE,
    question_id         bigint      NOT NULL REFERENCES questions (id),
    position            integer     NOT NULL,
    option_order        jsonb,                                 -- shuffled option ids
    is_answered         boolean     NOT NULL DEFAULT false,
    is_correct          boolean     NOT NULL DEFAULT false,
    is_flagged          boolean     NOT NULL DEFAULT false,
    hint_used           boolean     NOT NULL DEFAULT false,
    time_spent_seconds  integer     NOT NULL DEFAULT 0 CHECK (time_spent_seconds >= 0),
    answered_at         timestamptz,
    UNIQUE (attempt_id, position),
    UNIQUE (attempt_id, question_id)
);
CREATE INDEX ix_attempt_items_question ON attempt_items (question_id);   -- per-question stats (T-15, ADM-05)

CREATE TABLE attempt_item_options (
    attempt_item_id     bigint NOT NULL REFERENCES attempt_items (id) ON DELETE CASCADE,
    question_option_id  bigint NOT NULL REFERENCES question_options (id),
    PRIMARY KEY (attempt_item_id, question_option_id)
);
CREATE INDEX ix_attempt_item_options_option ON attempt_item_options (question_option_id);

-- ===================== MEMORIZATION =====================

CREATE TABLE review_cards (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           uuid         NOT NULL REFERENCES users (id),
    question_id       bigint       NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    state             text         NOT NULL DEFAULT 'New'
                      CHECK (state IN ('New', 'Learning', 'Review', 'Memorized')),
    due_at            timestamptz  NOT NULL DEFAULT now(),
    interval_days     numeric(8,2) NOT NULL DEFAULT 0 CHECK (interval_days >= 0),
    ease_factor       numeric(4,2) NOT NULL DEFAULT 2.50 CHECK (ease_factor > 0),
    repetitions       integer      NOT NULL DEFAULT 0 CHECK (repetitions >= 0),
    lapses            integer      NOT NULL DEFAULT 0 CHECK (lapses >= 0),
    last_reviewed_at  timestamptz,
    is_bookmarked     boolean      NOT NULL DEFAULT false,
    note              text,                                    -- learner's memory trick
    UNIQUE (user_id, question_id)
);
CREATE INDEX ix_review_cards_due ON review_cards (user_id, due_at);      -- daily review queue (M-08)
CREATE INDEX ix_review_cards_question ON review_cards (question_id);

CREATE TABLE review_logs (
    id                     bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_card_id         bigint       NOT NULL REFERENCES review_cards (id) ON DELETE CASCADE,
    rating                 text         NOT NULL CHECK (rating IN ('Forgot', 'Hard', 'Good', 'Easy')),
    interval_before_days   numeric(8,2) NOT NULL,
    interval_after_days    numeric(8,2) NOT NULL,
    reviewed_at            timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_review_logs_card ON review_logs (review_card_id, reviewed_at DESC);

-- ===================== MODERATION & AUDIT =====================

CREATE TABLE content_reports (
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_user_id     uuid        REFERENCES users (id),   -- NULL for guests
    question_id          bigint      REFERENCES questions (id),
    exam_id              bigint      REFERENCES exams (id),
    reason               text        NOT NULL,
    status               text        NOT NULL DEFAULT 'Open'
                         CHECK (status IN ('Open', 'Fixed', 'TakenDown', 'Rejected')),
    created_at           timestamptz NOT NULL DEFAULT now(),
    resolved_by_user_id  uuid        REFERENCES users (id),
    resolved_at          timestamptz,
    CHECK (num_nonnulls(question_id, exam_id) >= 1)
);
CREATE INDEX ix_content_reports_open ON content_reports (created_at) WHERE status = 'Open';  -- ADM-04
CREATE INDEX ix_content_reports_question ON content_reports (question_id);
CREATE INDEX ix_content_reports_exam ON content_reports (exam_id);
CREATE INDEX ix_content_reports_reporter ON content_reports (reporter_user_id);
CREATE INDEX ix_content_reports_resolver ON content_reports (resolved_by_user_id);

